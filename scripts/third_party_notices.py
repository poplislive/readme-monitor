"""Regenerate THIRD_PARTY_NOTICES.md from the interface's production dependencies.

The compiled interface in readme_monitor/web/ bundles these packages, so their licence texts
ship with every copy. Run from the repository root after `npm ci` in ui/:

    python scripts/third_party_notices.py
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI = ROOT / "ui"
LICENCE_NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE")


def main() -> int:
    out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--parseable"], cwd=UI,
                         capture_output=True, text=True, shell=sys.platform == "win32").stdout
    seen, packages = set(), []
    for line in out.splitlines()[1:]:
        folder = Path(line.strip())
        meta = json.loads((folder / "package.json").read_text(encoding="utf-8"))
        key = (meta["name"], meta["version"])
        if key in seen:
            continue
        seen.add(key)
        lic = meta.get("license")
        lic = lic.get("type") if isinstance(lic, dict) else lic
        texts = [p for p in sorted(folder.iterdir()) if p.is_file() and p.name.upper().startswith(LICENCE_NAMES)]
        if not texts:
            print(f"no licence file in {meta['name']} {meta['version']}", file=sys.stderr)
            return 1
        packages.append((meta["name"], meta["version"], lic or "see text", texts))
    packages.sort(key=lambda p: p[0])

    lines = [
        "# Third-party notices",
        "",
        "ReadmeMonitor is licensed under the Apache License 2.0 (see `LICENSE`). The compiled",
        "interface in `readme_monitor/web/` bundles the packages below, which keep their own licences.",
        "Python dependencies are installed separately and are not redistributed here.",
        "",
        "Generated by `scripts/third_party_notices.py`; do not edit by hand.",
        "",
        "| Package | Version | Licence |",
        "| --- | --- | --- |",
        *[f"| {n} | {v} | {lic} |" for n, v, lic, _ in packages],
        "",
    ]
    for name, version, lic, texts in packages:
        lines += [f"## {name} {version} ({lic})", ""]
        for t in texts:
            body = t.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            lines += ["```text", body.replace("```", "'''"), "```", ""]
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{len(packages)} packages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
